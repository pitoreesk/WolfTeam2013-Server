"""Generate go-gameserver/internal/game/exitem_use_2013.go from the 2013 TR
WT_Attributes\\ExItemData.dat (loader sub_340751D0).

Record: u32 item, u16, u16, u32, u8 use type (-> item +110, read by the
USEITEM ACK sub_34226820 and the use dialog sub_342279A0), 6 x u32, 5 x u32,
2 x {u16 n + UTF-16 path, u16, u16}. Coupon amounts are not stored in the
record; they come from the icon file name (e.g. exitem\\5000_GOLD.dtx), which
matches every USEITEM message present in the client string table
(7500 + type, e.g. 7548 "100 Altın").
"""
import os
import re
import struct

CLIENT = r"D:\WolfTeam2013\XFS\data\Root\wt_attributes\exitemdata.dat"
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "go-gameserver", "internal", "game", "exitem_use_2013.go")


def records(data):
    pos = 0
    while pos + 4 <= len(data):
        item, _, _, _, kind = struct.unpack_from("<IHHIB", data, pos)
        pos += 13 + 24 + 20
        paths = []
        for _ in range(2):
            n, = struct.unpack_from("<H", data, pos)
            pos += 2
            paths.append(data[pos:pos + 2 * n].decode("utf-16le"))
            pos += 2 * n + 4
        yield item, kind, paths[0]


def main():
    rows = []
    for item, kind, icon in records(open(CLIENT, "rb").read()):
        if kind == 0:
            continue
        name = icon.split("\\")[-1]
        match = re.match(r"(\d+)_?(GOLD|WC|GP)\.", name, re.I)
        gold = wc = gp = 0
        if match:
            amount, unit = int(match.group(1)), match.group(2).upper()
            gold, wc, gp = (amount if unit == "GOLD" else 0), (amount if unit == "WC" else 0), (amount if unit == "GP" else 0)
        rows.append((item, kind, gold, wc, gp, name))
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Code generated by tools/exitem/gen_exitem_use.py from 2013 TR ExItemData.dat; DO NOT EDIT.\n\n")
        fh.write("package game\n\n")
        fh.write("// exItemUses maps every usable EX item to its use type (item +110) and,\n")
        fh.write("// for coupons, the credited amount (from the item's icon name).\n")
        fh.write("var exItemUses = map[int]exItemUse{\n")
        for item, kind, gold, wc, gp, name in sorted(rows):
            fh.write(f"\t{item}: {{Type: {kind}, Gold: {gold}, WC: {wc}, GP: {gp}}}, // {name}\n")
        fh.write("}\n")
    print("wrote", len(rows), "entries to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
