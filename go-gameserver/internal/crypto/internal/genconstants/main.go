// Command genconstants generates the standard Blowfish initialization tables
// from the hexadecimal fractional digits of pi. Keeping the derivation here
// makes the origin of the values reproducible without importing an expanded
// schedule from another implementation.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"math/big"
	"os"
	"strconv"
)

const (
	pWords         = 18
	sBoxes         = 4
	sWords         = 256
	hexDigitsPer32 = 8
	guardHexDigits = 64
	outputName     = "zz_broker_constants.go"
)

func main() {
	wordCount := pWords + sBoxes*sWords
	digits := piFractionHexDigits(wordCount * hexDigitsPer32)
	words := make([]uint32, wordCount)
	for i := range words {
		value, err := strconv.ParseUint(digits[i*hexDigitsPer32:(i+1)*hexDigitsPer32], 16, 32)
		if err != nil {
			panic(err)
		}
		words[i] = uint32(value)
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	source.WriteString("package crypto\n\n")
	source.WriteString("// Standard Blowfish initialization words, derived from pi's hexadecimal fractional digits.\n")
	writeArray(&source, "brokerInitialP", words[:pWords], 0)
	source.WriteString("\nvar brokerInitialS = [4][256]uint32{\n")
	offset := pWords
	for box := 0; box < sBoxes; box++ {
		source.WriteString("\t{\n")
		writeWords(&source, words[offset:offset+sWords], 2)
		source.WriteString("\t},\n")
		offset += sWords
	}
	source.WriteString("}\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(outputName, formatted, 0o644); err != nil {
		panic(err)
	}
}

func writeArray(target *bytes.Buffer, name string, words []uint32, indent int) {
	fmt.Fprintf(target, "var %s = [%d]uint32{\n", name, len(words))
	writeWords(target, words, indent+1)
	target.WriteString("}\n")
}

func writeWords(target *bytes.Buffer, words []uint32, indent int) {
	for i, word := range words {
		if i%6 == 0 {
			for range indent {
				target.WriteByte('\t')
			}
		}
		fmt.Fprintf(target, "0x%08x,", word)
		if i%6 == 5 || i == len(words)-1 {
			target.WriteByte('\n')
		} else {
			target.WriteByte(' ')
		}
	}
}

// piFractionHexDigits returns the requested hexadecimal digits after the radix
// point. Chudnovsky's series supplies pi with extra guard digits; truncating the
// guarded result makes the emitted Blowfish constants deterministic.
func piFractionHexDigits(count int) string {
	total := count + guardHexDigits
	precision := uint(total*4 + 256)
	pi := chudnovskyPi(precision)

	fraction := new(big.Float).SetPrec(precision).Sub(pi, floatWithPrec(precision, 3))
	scaleInt := new(big.Int).Lsh(big.NewInt(1), uint(total*4))
	scale := new(big.Float).SetPrec(precision).SetInt(scaleInt)
	scaled := new(big.Float).SetPrec(precision).Mul(fraction, scale)
	digitsInt, _ := scaled.Int(nil)
	digits := fmt.Sprintf("%0*x", total, digitsInt)
	if len(digits) != total {
		panic(fmt.Sprintf("generated %d hexadecimal digits, want %d", len(digits), total))
	}
	return digits[:count]
}

func chudnovskyPi(precision uint) *big.Float {
	decimalDigits := float64(precision) * math.Log10(2)
	terms := int(math.Ceil(decimalDigits/14)) + 10

	m := floatWithPrec(precision, 1)
	l := floatWithPrec(precision, 13591409)
	x := floatWithPrec(precision, 1)
	sum := new(big.Float).SetPrec(precision).Set(l)
	k := int64(6)

	for i := int64(1); i < int64(terms); i++ {
		numerator := k*k*k - 16*k
		denominator := i * i * i
		m.Mul(m, floatWithPrec(precision, numerator))
		m.Quo(m, floatWithPrec(precision, denominator))
		l.Add(l, floatWithPrec(precision, 545140134))
		x.Mul(x, floatWithPrec(precision, -262537412640768000))

		term := new(big.Float).SetPrec(precision).Mul(m, l)
		term.Quo(term, x)
		sum.Add(sum, term)
		k += 12
	}

	squareRoot := new(big.Float).SetPrec(precision).Sqrt(floatWithPrec(precision, 10005))
	numerator := new(big.Float).SetPrec(precision).Mul(
		floatWithPrec(precision, 426880),
		squareRoot,
	)
	return new(big.Float).SetPrec(precision).Quo(numerator, sum)
}

func floatWithPrec(precision uint, value int64) *big.Float {
	return new(big.Float).SetPrec(precision).SetInt64(value)
}
