-- Server-relayed peer messages must survive an offline recipient. This
-- includes add (C041), accept (C042), and remove (C043) notifications.
CREATE TABLE IF NOT EXISTS buddy_mailbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_id integer NOT NULL CHECK (message_id BETWEEN 0 AND 65535),
    body bytea NOT NULL CHECK (octet_length(body) <= 51932),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (recipient_user_id <> sender_user_id)
);

CREATE INDEX IF NOT EXISTS buddy_mailbox_recipient_id_idx
    ON buddy_mailbox (recipient_user_id, id);
