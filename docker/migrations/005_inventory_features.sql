        ALTER TABLE inventory ADD CONSTRAINT inventory_paid_currency_check
            CHECK (paid_currency IN (0, 1, 2, 4));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'inventory_paid_price_check') THEN
