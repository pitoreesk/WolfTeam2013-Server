END $$;

CREATE TABLE IF NOT EXISTS equipped_titles (
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    slot smallint NOT NULL CHECK (slot BETWEEN 0 AND 3),
    title varchar(127) NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, slot)
);

CREATE TABLE IF NOT EXISTS permanent_item_tickets (
    item_id integer PRIMARY KEY CHECK (item_id BETWEEN 1 AND 65535),
    target_type smallint NOT NULL DEFAULT -1 CHECK (target_type IN (-1, 0, 1)),
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS daily_shop (
    active_day date PRIMARY KEY,
    item_a integer NOT NULL CHECK (item_a BETWEEN 1 AND 65535),
    item_b integer NOT NULL CHECK (item_b BETWEEN 1 AND 65535)
);

CREATE TABLE IF NOT EXISTS forge_recipes (
    category smallint NOT NULL CHECK (category BETWEEN 0 AND 255),
    challenge smallint NOT NULL CHECK (challenge BETWEEN 0 AND 255),
    choice_index smallint NOT NULL CHECK (choice_index BETWEEN 0 AND 255),
    cost_cash integer NOT NULL DEFAULT 0 CHECK (cost_cash >= 0),
    reward_item_id integer NOT NULL CHECK (reward_item_id BETWEEN 1 AND 65535),
    reward_days smallint NOT NULL DEFAULT 0 CHECK (reward_days BETWEEN 0 AND 3650),
    enabled boolean NOT NULL DEFAULT true,
    PRIMARY KEY (category, challenge, choice_index)
);

CREATE TABLE IF NOT EXISTS forge_wins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category smallint NOT NULL CHECK (category BETWEEN 0 AND 255),
    reward_item_id integer NOT NULL CHECK (reward_item_id BETWEEN 1 AND 65535),
    reward_days smallint NOT NULL DEFAULT 0 CHECK (reward_days BETWEEN 0 AND 3650),
    won_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS forge_wins_category_time_idx ON forge_wins (category, won_at DESC);

