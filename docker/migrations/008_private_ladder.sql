ALTER TABLE users
    ADD COLUMN IF NOT EXISTS ladder_points integer NOT NULL DEFAULT 0
        CHECK (ladder_points >= 0);

CREATE INDEX IF NOT EXISTS users_ladder_rank_idx
    ON users (ladder_points DESC, wins DESC, id);

CREATE TABLE IF NOT EXISTS private_ladder_notices (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(63) NOT NULL DEFAULT '',
    starts_on date,
    ends_on date,
    summary varchar(2047) NOT NULL DEFAULT '',
    details varchar(2047) NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_on IS NULL OR ends_on IS NULL OR starts_on <= ends_on)
);

CREATE INDEX IF NOT EXISTS private_ladder_notices_active_idx
    ON private_ladder_notices (enabled, created_at DESC);
