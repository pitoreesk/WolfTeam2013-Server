ALTER TABLE pride_battles ADD COLUMN IF NOT EXISTS score_b      integer      NOT NULL DEFAULT 0;
ALTER TABLE pride_battles ADD COLUMN IF NOT EXISTS earn_points  integer      NOT NULL DEFAULT 0;

-- Per-player battle performance
CREATE TABLE IF NOT EXISTS pride_battle_members (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    battle_id   bigint  NOT NULL REFERENCES pride_battles(id) ON DELETE CASCADE,
    user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kills       integer NOT NULL DEFAULT 0,
    deaths      integer NOT NULL DEFAULT 0,
    score       integer NOT NULL DEFAULT 0,
    is_ace      boolean NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS pride_battle_members_battle_idx ON pride_battle_members (battle_id);
