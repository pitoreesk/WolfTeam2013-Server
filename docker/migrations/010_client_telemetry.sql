CREATE TABLE IF NOT EXISTS client_telemetry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    session_id integer NOT NULL CHECK (session_id BETWEEN 0 AND 65535),
    provider varchar(16) NOT NULL CHECK (provider IN ('gameguard', 'xtrap', 'apex')),
    payload bytea NOT NULL DEFAULT ''::bytea CHECK (octet_length(payload) <= 65535),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS client_telemetry_user_time_idx
    ON client_telemetry (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS client_telemetry_provider_time_idx
    ON client_telemetry (provider, created_at DESC);
