-- In-game ranking menu (RankingSection, "Ranking Web Module"). The daily,
-- weekly and monthly boards need dated match results; users only keeps the
-- totals. Kills and deaths are already dated in kill_log.
CREATE TABLE IF NOT EXISTS ranking_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event       smallint NOT NULL CHECK (event BETWEEN 1 AND 4), -- 1 win, 2 loss, 3 draw, 4 GP
    amount      integer  NOT NULL DEFAULT 1 CHECK (amount >= 0),
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ranking_events_time_idx ON ranking_events (occurred_at, event);

-- Top-3 comments (CommentListTop3.aspx / UpdateCommentTop3.aspx). One comment
-- per board and owner (account, or the Pride id for Pride boards).
CREATE TABLE IF NOT EXISTS ranking_comments (
    rank_type   smallint NOT NULL,
    kind        smallint NOT NULL,
    period_type smallint NOT NULL,
    period      bigint   NOT NULL,
    main_type   bigint   NOT NULL,
    sub_type    bigint   NOT NULL,
    owner       varchar(20)  NOT NULL,
    comment     varchar(200) NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (rank_type, kind, period_type, period, main_type, sub_type, owner)
);
