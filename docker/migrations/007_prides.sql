CREATE TABLE IF NOT EXISTS prides (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY,
    name varchar(16) NOT NULL,
    master_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    intro varchar(127) NOT NULL DEFAULT '',
    notice varchar(127) NOT NULL DEFAULT '',
    rank_points integer NOT NULL DEFAULT 0 CHECK (rank_points >= 0),
    wins integer NOT NULL DEFAULT 0 CHECK (wins >= 0),
    losses integer NOT NULL DEFAULT 0 CHECK (losses >= 0),
    close_status smallint NOT NULL DEFAULT 0 CHECK (close_status BETWEEN 0 AND 255),
    close_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((close_status = 0) = (close_at IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS prides_name_ci_idx ON prides (lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS prides_master_idx ON prides (master_user_id);

CREATE TABLE IF NOT EXISTS pride_members (
    pride_id bigint NOT NULL REFERENCES prides(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role smallint NOT NULL DEFAULT 0 CHECK (role BETWEEN 0 AND 8),
    contribution integer NOT NULL DEFAULT 0 CHECK (contribution >= 0),
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (pride_id, user_id),
    UNIQUE (user_id)
);
CREATE INDEX IF NOT EXISTS pride_members_pride_role_idx ON pride_members (pride_id, role DESC, joined_at);

CREATE TABLE IF NOT EXISTS pride_applications (
    pride_id bigint NOT NULL REFERENCES prides(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    applied_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (pride_id, user_id)
);
CREATE INDEX IF NOT EXISTS pride_applications_user_idx ON pride_applications (user_id);

CREATE TABLE IF NOT EXISTS pride_memos (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY,
    pride_id bigint NOT NULL REFERENCES prides(id) ON DELETE CASCADE,
    author_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message varchar(127) NOT NULL CHECK (message <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pride_memos_pride_time_idx ON pride_memos (pride_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS pride_battles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pride_id bigint NOT NULL REFERENCES prides(id) ON DELETE CASCADE,
    opponent_pride_id bigint NOT NULL REFERENCES prides(id) ON DELETE CASCADE,
    won boolean NOT NULL,
    rank_delta smallint NOT NULL,
    played_at timestamptz NOT NULL DEFAULT now(),
    CHECK (pride_id <> opponent_pride_id)
);
CREATE INDEX IF NOT EXISTS pride_battles_pride_time_idx ON pride_battles (pride_id, played_at DESC);
