    paid_currency smallint NOT NULL DEFAULT 0 CHECK (paid_currency IN (0, 1, 2, 4)),
    paid_price bigint NOT NULL DEFAULT 0 CHECK (paid_price >= 0),
    acquired_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX inventory_user_item_idx ON inventory (user_id, item_id, id);

