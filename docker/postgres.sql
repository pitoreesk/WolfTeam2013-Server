CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(20) NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9_]{3,20}$'),
    password_hash text NOT NULL,
    callsign varchar(32) NOT NULL,
    level smallint NOT NULL DEFAULT 61 CHECK (level BETWEEN 1 AND 61),
    gp integer NOT NULL DEFAULT 0 CHECK (gp >= 0),
    gold integer NOT NULL DEFAULT 0 CHECK (gold >= 0),
    wc integer NOT NULL DEFAULT 0 CHECK (wc >= 0),
    cash integer NOT NULL DEFAULT 0 CHECK (cash >= 0),
    kills integer NOT NULL DEFAULT 0 CHECK (kills >= 0),
    deaths integer NOT NULL DEFAULT 0 CHECK (deaths >= 0),
    wins integer NOT NULL DEFAULT 0 CHECK (wins >= 0),
    losses integer NOT NULL DEFAULT 0 CHECK (losses >= 0),
    ladder_points integer NOT NULL DEFAULT 0 CHECK (ladder_points >= 0),
	 school_id bigint NOT NULL DEFAULT 0 CHECK (school_id BETWEEN 0 AND 4294967294),
	 school_value bigint NOT NULL DEFAULT 0 CHECK (school_value BETWEEN 0 AND 4294967295),
	 wolf_points bigint NOT NULL DEFAULT 0 CHECK (wolf_points BETWEEN 0 AND 4294967295),
    last_login timestamptz
);
CREATE INDEX users_ladder_rank_idx ON users (ladder_points DESC, wins DESC, id);
CREATE UNIQUE INDEX users_callsign_ci_idx ON users (lower(callsign));

CREATE TABLE recommendations (
    requester_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status smallint NOT NULL DEFAULT 0 CHECK (status BETWEEN 0 AND 2),
    created_at timestamptz NOT NULL DEFAULT now(),
    answered_at timestamptz,
    PRIMARY KEY (requester_user_id, target_user_id),
    CHECK (requester_user_id <> target_user_id),
    CHECK ((status = 0) = (answered_at IS NULL))
);
CREATE INDEX recommendations_target_status_idx
    ON recommendations (target_user_id, status, created_at);

CREATE TABLE buddy_relations (
    owner_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    buddy_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    group_id integer NOT NULL DEFAULT 0 CHECK (group_id BETWEEN 0 AND 65535),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (owner_user_id, buddy_user_id),
    CHECK (owner_user_id <> buddy_user_id)
);
CREATE INDEX buddy_relations_buddy_idx ON buddy_relations (buddy_user_id, created_at);

CREATE TABLE buddy_mailbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_id integer NOT NULL CHECK (message_id BETWEEN 0 AND 65535),
    body bytea NOT NULL CHECK (octet_length(body) <= 51932),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (recipient_user_id <> sender_user_id)
);
CREATE INDEX buddy_mailbox_recipient_id_idx ON buddy_mailbox (recipient_user_id, id);

CREATE TABLE client_telemetry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    session_id integer NOT NULL CHECK (session_id BETWEEN 0 AND 65535),
    provider varchar(16) NOT NULL CHECK (provider IN ('gameguard', 'xtrap', 'apex')),
    payload bytea NOT NULL DEFAULT ''::bytea CHECK (octet_length(payload) <= 65535),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX client_telemetry_user_time_idx
    ON client_telemetry (user_id, created_at DESC);
CREATE INDEX client_telemetry_provider_time_idx
    ON client_telemetry (provider, created_at DESC);

CREATE TABLE private_ladder_notices (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(63) NOT NULL DEFAULT '',
    starts_on date,
    ends_on date,
    summary varchar(2047) NOT NULL DEFAULT '',
    details varchar(2047) NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_on IS NULL OR ends_on IS NULL OR starts_on <= ends_on)
);
CREATE INDEX private_ladder_notices_active_idx
    ON private_ladder_notices (enabled, created_at DESC);

CREATE TABLE inventory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id integer NOT NULL CHECK (item_id > 0),
    type smallint NOT NULL DEFAULT 0 CHECK (type IN (0, 1)),
