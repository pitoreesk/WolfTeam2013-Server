CREATE TABLE prides (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY,
    name varchar(16) NOT NULL,
    master_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    intro varchar(127) NOT NULL DEFAULT '',
    notice varchar(127) NOT NULL DEFAULT '',
    rank_points integer NOT NULL DEFAULT 0 CHECK (rank_points >= 0),
    wins integer NOT NULL DEFAULT 0 CHECK (wins >= 0),
    losses integer NOT NULL DEFAULT 0 CHECK (losses >= 0),
    close_status smallint NOT NULL DEFAULT 0 CHECK (close_status BETWEEN 0 AND 255),
    close_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((close_status = 0) = (close_at IS NULL))
);
CREATE UNIQUE INDEX prides_name_ci_idx ON prides (lower(name));
CREATE UNIQUE INDEX prides_master_idx ON prides (master_user_id);

