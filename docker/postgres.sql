CREATE TABLE gifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY,
    sender_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id integer NOT NULL CHECK (item_id BETWEEN 1 AND 65535),
    item_type smallint NOT NULL DEFAULT 0 CHECK (item_type IN (0, 1)),
    days smallint NOT NULL DEFAULT 0 CHECK (days BETWEEN 0 AND 3650),
    message varchar(127) NOT NULL DEFAULT '',
    status smallint NOT NULL DEFAULT 0 CHECK (status BETWEEN 0 AND 2),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL DEFAULT (now() + INTERVAL '90 days'),
    claimed_at timestamptz,
    CHECK (sender_user_id <> recipient_user_id),
    CHECK ((status = 2) = (claimed_at IS NOT NULL))
);
CREATE INDEX gifts_recipient_page_idx ON gifts (recipient_user_id, status, created_at DESC, id DESC);
CREATE INDEX gifts_sender_page_idx ON gifts (sender_user_id, status, created_at DESC, id DESC);
CREATE INDEX gifts_expiry_idx ON gifts (expires_at);

CREATE TABLE gift_components (
